    % Calculate derived metrics
    LossReduction_pct(i) = (Loss_baseline_pu - TotalLoss_pu(i)) / Loss_baseline_pu * 100;
    VoltageRecovery_pu(i) = Vmin_pu(i) - Vmin_baseline_pu;
    TotalSupportDevices(i) = N_ES(i) + N_STATCOM(i) + N_ESS(i) + N_ES1(i);
    TotalTraditionalSupport(i) = N_STATCOM(i) + N_ESS(i);
    TotalESBasedDevices(i) = N_ES(i) + N_ES1(i);
end

