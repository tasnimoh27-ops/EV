%% run_device_composition_analysis.m
% DEVICE COMPOSITION AND INSTALLED CAPACITY ANALYSIS
%
% Purpose:
%   Lightweight post-processing script to answer the research questions:
%   1. Individually, how many devices are required to make the stressed IEEE 33-bus feeder voltage-feasible?
%   2. In hybrid combinations, how many devices of each type are required?
%   3. What is the installed rating/capacity of each solution, not only the device count?
%   4. Which composition gives the best overall outcome when considering voltage feasibility,
%      Vmin/Vmax, total loss, device count, installed capacity, and practical interpretation?
%
% This script does NOT rerun optimisation and does NOT modify solver results.
% It uses the final reported cases and generates a comprehensive composition analysis
% with installed ratings, loss metrics, and recommendation categories.
%
% Interpretation notes:
%   - STATCOM and ES-1 are compared using installed MVAr because both have explicit reactive-power limits.
%   - Standard ES is reported as controllable non-critical-load capacity, not MVAr injection.
%   - ESS requires inverter MVA and battery MWh normalisation (marked if not available).
%   - PV is reported by installed MW capacity at the reference scale.
%
% Output:
%   04_results/es_framework/tables/table_device_composition_analysis.csv
%   04_results/es_framework/figures/fig_device_composition_feasibility.png
%   04_results/es_framework/figures/fig_device_composition_loss.png
%   04_results/es_framework/figures/fig_device_composition_device_count.png
%   04_results/es_framework/figures/fig_device_composition_installed_capacity.png

