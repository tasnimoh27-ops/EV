%% Base assumptions from the existing study
Sbase_MVA = 10.0;
Qs_max_pu = 0.10;           % STATCOM per-device reactive limit
Qes_max_pu = 0.10;          % ES-1 per-device reactive limit

rho = 0.70;                 % Standard ES engagement factor
u_min = 0.20;               % Standard ES minimum utilisation
P_total_peak_pu = 0.4458;   % Peak active load (pu at hour 20)
Q_total_peak_pu = 0.2760;   % Peak reactive load (pu at hour 20)
PV_ref_scale = 2.7;         % Stage 10 PV reference capacity (MW)
PV_max_scale = 2.0;         % Maximum PV scale in tested sweep (multiplier of reference)

% No support case loss and voltage (baseline for comparison)
Loss_baseline_pu = 0.6711;
Vmin_baseline_pu = 0.8308;

% Derived system-level values
P_peak_MW = P_total_peak_pu * Sbase_MVA;
Q_peak_MVAr = Q_total_peak_pu * Sbase_MVA;
S_peak_MVA = sqrt(P_peak_MW^2 + Q_peak_MVAr^2);

ControllableLoadP_MW = rho * P_peak_MW;
ControllableLoadQ_MVAr = rho * Q_peak_MVAr;
ControllableLoadS_MVA = rho * S_peak_MVA;
MaxReducibleP_MW = ControllableLoadP_MW * (1 - u_min);
MaxReducibleQ_MVAr = ControllableLoadQ_MVAr * (1 - u_min);
MaxReducibleS_MVA = ControllableLoadS_MVA * (1 - u_min);

STATCOM_per_device_MVAr = Qs_max_pu * Sbase_MVA;
ES1_per_device_MVAr = Qes_max_pu * Sbase_MVA;

